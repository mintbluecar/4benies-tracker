#!/usr/bin/env bash
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "$0")" && pwd)"
ROOT_DIR="$(cd "$SCRIPT_DIR/.." && pwd)"
SNAPSHOTS_DIR="$ROOT_DIR/snapshots"

if [ ! -d "$SNAPSHOTS_DIR" ]; then
  echo "No snapshots directory at $SNAPSHOTS_DIR — nothing to migrate."
  exit 0
fi

migrated=0
skipped=0

for playlist_dir in "$SNAPSHOTS_DIR"/*/; do
  [ -d "$playlist_dir" ] || continue
  for file in "$playlist_dir"*.json; do
    [ -f "$file" ] || continue
    base=$(basename "$file" .json)

    # Skip files already in the new format (contain 'T')
    if [[ "$base" == *T* ]]; then
      echo "  skip (already migrated): $file"
      skipped=$((skipped + 1))
      continue
    fi

    # Validate old format YYYY-MM-DD
    if [[ ! "$base" =~ ^[0-9]{4}-[0-9]{2}-[0-9]{2}$ ]]; then
      echo "  skip (unrecognized name): $file"
      skipped=$((skipped + 1))
      continue
    fi

    # Use midnight UTC of the recorded date — a safe lower bound. Real capture
    # time for legacy snapshots is unknown; we only know they represent the
    # state on their snapshot_date. Any new snapshot on the same day will have
    # a later snapshot_time and sort correctly.
    new_time="${base}T00:00:00Z"
    new_name="${base}T000000Z.json"
    new_path="${playlist_dir}${new_name}"

    if [ -e "$new_path" ]; then
      echo "  skip (target exists): $new_path"
      skipped=$((skipped + 1))
      continue
    fi

    # Rewrite JSON with snapshot_time added, write to new path, then remove old
    jq --arg t "$new_time" '. + {snapshot_time: $t}' "$file" > "$new_path"
    rm "$file"
    echo "  migrated: $(basename "$file") -> $new_name"
    migrated=$((migrated + 1))
  done
done

# Force regeneration by removing the stale index
if [ -f "$SNAPSHOTS_DIR/index.json" ]; then
  rm "$SNAPSHOTS_DIR/index.json"
  echo "Removed stale index.json (will be regenerated by snapshot.sh)."
fi

echo ""
echo "Migration done. Migrated: $migrated. Skipped: $skipped."
